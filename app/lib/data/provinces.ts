/** 获取所有城市（扁平化） */
export function getAllCities(): string[] {
  return PROVINCES.flatMap((p) => p.cities);
}

/** 根据省份名获取城市列表 */
export function getCitiesByProvince(province: string): string[] {
  return PROVINCES.find((p) => p.province === province)?.cities ?? [];
}

/** 根据城市名获取省份 */
export function getProvinceByCity(city: string): string | undefined {
  return PROVINCES.find((p) => p.cities.includes(city))?.province;
}
